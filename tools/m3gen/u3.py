def walk(x):
    if isinstance(x,dict):
        t=x.get('t')
        if t in ('triArea','paraArea','missingDim'):
            if t=='triArea': A=x['b']*x['h']/2; cands=[A,x['b']*x['h'],x.get('side',0) and x['b']*x['side']/2,x['b']+x['h']]
            elif t=='paraArea': A=x['b']*x['h']; cands=[A,A/2]
            else: k=2 if x['fig']=='tri' else 1; A=k*x['A']/x['v']; cands=[A,x['A']/x['v'],x['A']/2]
            for v in cands+[c+d for c in cands[:1] for d in (1,-1,2,-2,4,-4,10,-10)]:
                if v and v>0 and v<=100 and not float(v).is_integer() and float(v*2).is_integer(): HALVES.add(int(v))
        for v in x.values(): walk(v)
    elif isinstance(x,list):
        for v in x: walk(v)
