def unitphrase(n,u):   # عدد صحيح بوحدته
    if u=='n': return bigphrase(n)
    W=UN[u]
    if n==1: return W['one']
    if n==2: return W['two']
    if n<=10: return FEW[n]+' '+W['few']
    if n<100: return tens(n)+' '+W['many']
    h,r=divmod(n,100)
    if n<1000:
        if r==0: return H_CON[h]+' '+W['gen']
        if r<=2: return H_NOM[h]+' وَ'+(W['one'] if r==1 else W['two'])
        if r<=10: return H_NOM[h]+' وَ'+FEW[r]+' '+W['few']
        return H_NOM[h]+' وَ'+tens(r)+' '+W['many']
    raise ValueError(n)
def bigphrase(n):
    if n==0: return 'صِفْرٌ'
    if n<=10: return U1[n]
    if n<100: return tens(n)
    return below(n,False)
def frac_t(t):
    if t==1: return 'عُشْرٌ'
    if t==2: return 'عُشْرَانِ'
    return FEW[t]+' أَعْشَارٍ'
def frac_h(h):
    if h==1: return 'جُزْءٌ مِنْ مِئَةٍ'
    if h==2: return 'جُزْآنِ مِنْ مِئَةٍ'
    if h<=10: return FEW[h]+' أَجْزَاءٍ مِنْ مِئَةٍ'
    return tens(h)+' جُزْءًا مِنْ مِئَةٍ'
